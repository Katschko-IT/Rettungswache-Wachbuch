from django.contrib.auth.models import User
from django.test import TestCase
from django.urls import reverse

from core.display_views import notify_station_display
from core.models import Membership, Station


class DisplayStreamTests(TestCase):
    def setUp(self):
        self.station = Station.objects.create(
            name="Rettungswache Test Stream",
            slug="rw-test-stream",
            display_enabled=True,
        )
        self.user = User.objects.create_user(
            username="stream_user",
            password="testpassword123",
        )
        self.membership = Membership.objects.create(
            user=self.user,
            station=self.station,
            role=Membership.Role.SHIFT_LEAD,
            is_active=True,
        )
        self.client.force_login(self.user)

    def test_display_stream_endpoint(self):
        resp = self.client.get(reverse("display_stream"))
        self.assertEqual(resp.status_code, 200)
        self.assertEqual(resp["Content-Type"], "text/event-stream")
        self.assertIn("no-cache", resp["Cache-Control"])
        self.assertIn("no-transform", resp["Cache-Control"])
        self.assertEqual(resp["X-Accel-Buffering"], "no")

        # Test initial chunk generated by stream
        iterator = resp.streaming_content
        first_event = next(iterator)
        self.assertIn(b"event: update\ndata: {", first_event)
        self.assertIn(b"Rettungswache Test Stream", first_event)

    def test_notify_station_display_graceful(self):
        # Should not raise exception even without active Redis instance
        notify_station_display(self.station.id)
